def main(原始分数表: list[dict], 互评权重: float, 评审权重: float, 项目类别: str) -> dict:
    def 含(d: str, 词们) -> bool:
        return any(w in d for w in 词们)

    def 去极值均值(们: list) -> float:
        vs = sorted(们)
        if len(vs) >= 3:
            vs = vs[1:-1]
        return round(sum(vs) / len(vs), 2) if vs else 0.0

    互评权重 = float(互评权重 or 0.4)
    评审权重 = float(评审权重 or 0.6)
    类别 = (项目类别 or "科技").strip()
    是管理 = "管理" in 类别
    # 方案规定：管理类互评仅第一梯队、推荐前30%；科技类互评第一、二梯队、推荐前60%
    互评梯队 = ("第一梯队",) if 是管理 else ("第一梯队", "第二梯队")

    入围们 = []
    落选们 = []
    提示 = []
    仅有评审数 = 0
    有梯队信息 = False

    for 项 in (原始分数表 or []):
        if not isinstance(项, dict):
            continue
        名 = str(项.get("项目名称", "") or "")
        部门 = str(项.get("提报部门", "") or "")
        梯队 = str(项.get("梯队自评", "") or "")
        if 梯队:
            有梯队信息 = True
        评分 = 项.get("各部门评分") or {}
        if not isinstance(评分, dict):
            评分 = {}
        评分 = {str(k): float(v) for k, v in 评分.items() if isinstance(v, (int, float))}

        入互评 = 含(梯队, 互评梯队)
        if 梯队 and not 入互评:
            资格 = "落选"
        elif 梯队:
            资格 = "入围"
        else:
            资格 = "待核"  # 无梯队信息，不误杀，单独提示
            提示.append(f"「{名}」未提供梯队自评，默认按入围处理，请人工核实")

        # 领导评审：所有参评项目
        评审分 = [v for d, v in 评分.items() if 含(d, ("领导", "评审"))]
        评审均 = 去极值均值(评审分)
        # 部门互评：仅入围梯队项目计入
        互评分 = [v for d, v in 评分.items() if not 含(d, ("领导", "评审", "自评"))] if 资格 != "落选" else []
        互评均 = 去极值均值(互评分)

        if 资格 == "落选":
            落选们.append({"项目名称": 名, "提报部门": 部门, "梯队自评": 梯队,
                           "互评均值": 0.0, "评审均值": 评审均, "获评部门数": len(评分),
                           "总成绩": 评审均, "计算构成": f"第三梯队不互评，按评审分{评审均}参与优秀奖排序" if 评审均 else "第三梯队不互评，暂无评审分",
                           "排名": 0, "是否建议推荐": False})
            continue

        if 评审均 > 0 and 互评均 > 0:
            总 = round(互评均 * 互评权重 + 评审均 * 评审权重, 2)
            构成 = f"互评{互评均}×{互评权重}+评审{评审均}×{评审权重}"
        elif 互评均 > 0:
            总 = 互评均
            构成 = f"仅有互评分{互评均}（未识别评审分，未加权）"
            提示.append(f"「{名}」未识别到领导评审分，暂按互评分计")
        elif 评审均 > 0:
            总 = 评审均
            构成 = f"仅有评审分{评审均}（未识别互评分，未加权）"
            仅有评审数 += 1
        else:
            总 = 0.0
            构成 = "暂无任何评分"
            提示.append(f"「{名}」暂无互评/领导评分")
        入围们.append({"项目名称": 名, "提报部门": 部门, "梯队自评": 梯队,
                       "互评均值": 互评均, "评审均值": 评审均, "获评部门数": len(评分),
                       "总成绩": 总, "计算构成": 构成})

    入围们.sort(key=lambda x: -x["总成绩"])
    for i, r in enumerate(入围们):
        r["排名"] = i + 1
        r["是否建议推荐"] = True
    # 落选项目按评审分排序，前60%（管理类前30%）标为中心优秀奖候选
    落选们.sort(key=lambda x: -x["总成绩"])
    优数 = max(1, round(len(落选们) * (0.3 if 是管理 else 0.6))) if 落选们 else 0
    for i, r in enumerate(落选们):
        r["优秀奖候选"] = i < 优数
    结果 = 入围们 + 落选们

    行们 = []
    if 入围们:
        梯说明 = "第一梯队" if 是管理 else "第一、二梯队"
        行们.append(f"【季度入围推荐名单（{类别}类，{梯说明}共{len(入围们)}项，成绩=互评×{互评权重}+评审×{评审权重}）】")
        for r in 入围们:
            梯 = f"[{r['梯队自评']}]" if r["梯队自评"] else ""
            行们.append(f"{r['排名']}. {r['项目名称']}{梯} —— {r['总成绩']}分（{r['计算构成']}）")
    else:
        行们.append(f"⚠️无入围项目——请确认已上传含「梯队自评」列的自评表（{类别}类应含{梯说明}）")
    if 落选们:
        行们.append(f"\n【入库未入围（共{len(落选们)}项，按评审分排序，前{优数}项为中心优秀奖候选★）】")
        for r in 落选们:
            星 = "★" if r.get("优秀奖候选") else ""
            行们.append(f"· {星}{r['项目名称']}[{r['梯队自评']}]（{r['提报部门']}）评审{r['评审均值']}分")
    报告 = "\n".join(行们)
    if 仅有评审数:
        提示.append(f"有{仅有评审数}个入围项目未识别到互评分（互评表是否覆盖{梯说明}？），暂按评审分计")
    if not 有梯队信息:
        提示.append("⚠️所有项目均无梯队自评信息——请上传自评表，否则无法执行梯队筛选")
    if 提示:
        报告 += "\n\n⚠️注意：\n" + "\n".join(dict.fromkeys(提示))

    return {"score_rank_table": 结果, "score_report": 报告,
            "project_count": len(结果), "recommend_count": len(入围们)}
